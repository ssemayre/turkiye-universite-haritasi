/**
 * FIX-CAMPUSES.CJS
 * ================
 * 1. Mükerrer (< 300m arası) yerleşkeleri birleştir: MYO'yu kapsayıcı yerleşkeye ekle
 * 2. Jitter/Math.random ile kaydırılmış koordinatları tespit et
 *    - Aynı üniversitedeki ana kampüse çok yakın (<300m) MYO kayıtlarını ANA kampüse bağla
 * 3. Türkiye sınırları dışındaki koordinatları temizle
 * 4. campuses.json'u güncelle
 */

const fs = require('fs');

const campusesData = JSON.parse(fs.readFileSync('src/data/campuses.json', 'utf8'));

function haversineDistance(lat1, lon1, lat2, lon2) {
    const R = 6371000;
    const dLat = (lat2 - lat1) * Math.PI / 180;
    const dLon = (lon2 - lon1) * Math.PI / 180;
    const a = Math.sin(dLat/2)*Math.sin(dLat/2) +
              Math.cos(lat1 * Math.PI/180)*Math.cos(lat2 * Math.PI/180)*
              Math.sin(dLon/2)*Math.sin(dLon/2);
    return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1-a));
}

function isTurkeyBounds(lat, lng) {
    return lat >= 35.9 && lat <= 42.1 && lng >= 25.6 && lng <= 44.8;
}

function isMYOCampus(c) {
    return c.name && (c.name.includes('(MYO)') || c.name.toUpperCase().includes('MESLEK YÜKSEK'));
}

function isStandaloneUnit(c) {
    // These were created by extract-myos.cjs with jitter - identifiable by autoGenerated field
    // or by being a "(MYO)" campus
    return isMYOCampus(c) && (c.autoGenerated || (c.id && c.id.includes('-campus-')));
}

let mergedCount = 0;
let removedJitterCount = 0;
let fixedBoundsCount = 0;
let toRemoveIds = new Set();

for (const [uniKey, uni] of Object.entries(campusesData)) {
    const campuses = uni.campuses || [];
    
    // 1. Find real (non-MYO) campuses with coordinates
    const realCampuses = campuses.filter(c => c.latitude && c.longitude && !isMYOCampus(c));
    
    // 2. Find standalone MYO campuses
    const myoCampuses = campuses.filter(c => isStandaloneUnit(c));
    
    for (const myoCampus of myoCampuses) {
        const myoLat = parseFloat(myoCampus.latitude);
        const myoLng = parseFloat(myoCampus.longitude);
        
        if (!myoLat || !myoLng) continue;
        
        // Check if it's within 300m of a real campus → it's a jitter artifact, merge it
        let closestRealCampus = null;
        let closestDist = Infinity;
        
        for (const realCampus of realCampuses) {
            const d = haversineDistance(
                myoLat, myoLng,
                parseFloat(realCampus.latitude), parseFloat(realCampus.longitude)
            );
            if (d < closestDist) {
                closestDist = d;
                closestRealCampus = realCampus;
            }
        }
        
        // If MYO is within 300m of a real campus, it's likely a jitter artifact → merge
        if (closestRealCampus && closestDist < 300) {
            // Move academic units from the MYO campus to the real campus
            if (!closestRealCampus.academicUnits) closestRealCampus.academicUnits = [];
            
            // Merge academic units
            for (const au of (myoCampus.academicUnits || [])) {
                const alreadyExists = closestRealCampus.academicUnits.some(
                    existing => existing.name.toUpperCase() === au.name.toUpperCase()
                );
                if (!alreadyExists) {
                    closestRealCampus.academicUnits.push(au);
                }
            }
            
            // Merge faculty names
            if (!closestRealCampus.facultyNames) closestRealCampus.facultyNames = [];
            for (const fn of (myoCampus.facultyNames || [])) {
                if (!closestRealCampus.facultyNames.includes(fn)) {
                    closestRealCampus.facultyNames.push(fn);
                }
            }
            
            // Mark for removal
            toRemoveIds.add(myoCampus.id);
            removedJitterCount++;
            console.log(`[JITTER MERGE] "${myoCampus.name}" (${closestDist.toFixed(0)}m) → "${closestRealCampus.name}" [${uni.universityName.substring(0, 40)}]`);
        }
    }
    
    // 3. Find non-MYO duplicate pairs (two real campuses very close together)
    const remaining = realCampuses.filter(c => !toRemoveIds.has(c.id));
    for (let i = 0; i < remaining.length; i++) {
        for (let j = i+1; j < remaining.length; j++) {
            if (toRemoveIds.has(remaining[i].id) || toRemoveIds.has(remaining[j].id)) continue;
            const d = haversineDistance(
                parseFloat(remaining[i].latitude), parseFloat(remaining[i].longitude),
                parseFloat(remaining[j].latitude), parseFloat(remaining[j].longitude)
            );
            if (d < 150) {
                // Merge the newer/auto-generated one into the older/official one
                const keepCampus = remaining[i].autoGenerated ? remaining[j] : remaining[i];
                const removeCampus = remaining[i].autoGenerated ? remaining[i] : remaining[j];
                
                if (!keepCampus.academicUnits) keepCampus.academicUnits = [];
                for (const au of (removeCampus.academicUnits || [])) {
                    const exists = keepCampus.academicUnits.some(e => e.name.toUpperCase() === au.name.toUpperCase());
                    if (!exists) keepCampus.academicUnits.push(au);
                }
                if (!keepCampus.facultyNames) keepCampus.facultyNames = [];
                for (const fn of (removeCampus.facultyNames || [])) {
                    if (!keepCampus.facultyNames.includes(fn)) keepCampus.facultyNames.push(fn);
                }
                
                toRemoveIds.add(removeCampus.id);
                mergedCount++;
                console.log(`[MERGE] "${removeCampus.name}" (${d.toFixed(0)}m) → "${keepCampus.name}" [${uni.universityName.substring(0, 40)}]`);
            }
        }
    }
    
    // 4. Fix Derbent+KartepeMYO specifically (1080m apart but same physical place)
    // This is the case where both are "real" campuses but one is just the MYO building inside the other's campus
    // We detect this by: one has name "Derbent Yerleşkesi" and the other "KARTEPE TURİZM Yerleşkesi (MYO)" within 2km
    const derbentCampus = campuses.find(c => c.name.includes('Derbent') && !toRemoveIds.has(c.id));
    const kartepeMyo = campuses.find(c => c.name.includes('KARTEPE TURİZM') && !toRemoveIds.has(c.id));
    
    if (derbentCampus && kartepeMyo) {
        const d = haversineDistance(
            parseFloat(derbentCampus.latitude), parseFloat(derbentCampus.longitude),
            parseFloat(kartepeMyo.latitude), parseFloat(kartepeMyo.longitude)
        );
        if (d < 2000) {
            // Merge Kartepe Turizm MYO into Derbent campus, rename Derbent to reflect this
            if (!derbentCampus.academicUnits) derbentCampus.academicUnits = [];
            for (const au of (kartepeMyo.academicUnits || [])) {
                const exists = derbentCampus.academicUnits.some(e => e.name.toUpperCase() === au.name.toUpperCase());
                if (!exists) derbentCampus.academicUnits.push(au);
            }
            if (!derbentCampus.facultyNames) derbentCampus.facultyNames = [];
            for (const fn of (kartepeMyo.facultyNames || [])) {
                if (!derbentCampus.facultyNames.includes(fn)) derbentCampus.facultyNames.push(fn);
            }
            // Use the more precise MYO coordinate (geocoded from real address)
            derbentCampus.latitude = kartepeMyo.latitude;
            derbentCampus.longitude = kartepeMyo.longitude;
            
            toRemoveIds.add(kartepeMyo.id);
            mergedCount++;
            console.log(`[DERBENT MERGE] "KARTEPE TURİZM Yerleşkesi (MYO)" (${d.toFixed(0)}m) → "Derbent Yerleşkesi"`);
        }
    }
    
    // 5. Remove out-of-bounds campuses
    for (const c of campuses) {
        if (toRemoveIds.has(c.id)) continue;
        const lat = parseFloat(c.latitude), lng = parseFloat(c.longitude);
        if (lat && lng && !isTurkeyBounds(lat, lng)) {
            console.log(`[OOB] "${c.name}" lat=${lat} lng=${lng} [${uni.universityName.substring(0, 40)}]`);
            fixedBoundsCount++;
            // Don't delete, just clear coordinates so it doesn't show a wrong pin
            c.latitude = null;
            c.longitude = null;
            c.coordinateStatus = 'out-of-bounds-cleared';
        }
        
        // Also fix reversed lat/lng (lat should be ~36-42 for Turkey, lng ~26-45)
        if (lat && lng && lat > 44 && lng < 42) {
            console.log(`[REVERSED] "${c.name}" was lat=${lat} lng=${lng} - SWAPPING`);
            c.latitude = lng;
            c.longitude = lat;
            fixedBoundsCount++;
        }
    }
    
    // Remove merged campuses from this university
    uni.campuses = campuses.filter(c => !toRemoveIds.has(c.id));
}

// Write the updated data
fs.writeFileSync('src/data/campuses.json', JSON.stringify(campusesData, null, 2));

console.log('\n=== SUMMARY ===');
console.log('Jitter artifacts merged into real campuses:', removedJitterCount);
console.log('Duplicate real campuses merged:', mergedCount);
console.log('Out-of-bounds coordinates cleared:', fixedBoundsCount);
console.log('Total campuses removed:', toRemoveIds.size);
